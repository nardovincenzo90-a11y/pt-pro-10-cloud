if(!index.includes('10.0.0-rc1'))throw new Error('Release gate: index non è RC1');
const ui=fs.readFileSync('ux-unifier.js','utf8');
for(const t of ['Prontezza e fatica','Cloud connesso','Allenamenti settimana','Carboidrati'])if(!ui.includes(t))throw new Error('Release gate: localizzazione mancante '+t);
const nutri=fs.readFileSync('nutrition-runtime-evolution.js','utf8');
for(const t of ['nutrition_days','meals?select','meal_items','api_saveNutritionSmartDay'])if(!nutri.includes(t))throw new Error('Release gate: persistenza nutrizione incompleta '+t);
